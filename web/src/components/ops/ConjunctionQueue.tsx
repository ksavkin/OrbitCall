function EventRow({ e, now }: { e: ConjunctionEvent; now: number }) {
  const focused = useOps((s) => s.focusEvent === e.id);
  const owners = useOrbit((s) => s.catalog?.owners ?? NO_OWNERS);
  const st = STATUS_META[e.status];
  const resolved = RESOLVED.includes(e.status);
  const trend = e.trend === "rising" ? ArrowUpRight : e.trend === "falling" ? ArrowDownRight : ArrowRight;
  const TrendIcon = trend;
  const fa = ownerInfo(e.a.owner, owners);
  const fb = ownerInfo(e.b.owner, owners);

  return (
    <div
      className="group relative mb-1 overflow-hidden rounded-[11px] transition-colors duration-200"
      style={{
        background: focused ? "rgba(255,255,255,0.055)" : undefined,
        boxShadow: focused ? "inset 0 0 0 1px rgba(255,255,255,0.09)" : undefined,
      }}
    >
      {e.agentsWorking && <span className="agent-sheen pointer-events-none absolute inset-0 rounded-[11px]" />}
      <button
        className="relative block w-full px-2.5 py-2 text-left transition-colors hover:bg-white/[0.035]"
        onClick={() => {
          sfx.select();
          const st = useOps.getState();
          // the case being worked opens its command view instead of the inline details
          if (st.incident === e.id) {
            st.set({ focusEvent: e.id, incidentView: "expanded" });
            return;
          }
          st.set({ focusEvent: focused ? null : e.id });
        }}
        onPointerEnter={() => sfx.hover()}
      >
        {/* risk rail */}
        <span
          className="absolute bottom-2 left-0 top-2 w-[2px] rounded-full"
          style={{ background: resolved ? "rgba(255,255,255,0.15)" : RISK_COLOR[e.risk], boxShadow: resolved ? undefined : `0 0 8px ${RISK_COLOR[e.risk]}` }}
        />
        <div className="flex items-center gap-1.5">
          <span className="mono text-[10px] text-muted">{e.id}</span>
          <span className="ml-auto mono tnum text-[10.5px]" style={{ color: e.tca - now < 24 * 3600_000 && !resolved ? "var(--orange)" : "var(--fg-2)" }}>
            {now ? fmtCountdown(e.tca - now) : "—"}
          </span>
        </div>
        <div className="mt-1 flex min-w-0 items-center gap-1.5 text-[12px] font-medium tracking-[-0.005em]">
          {fa && fa.flags[0] && <Flag code={fa.flags[0]} h={10} />}
          <span className="truncate">{e.a.name}</span>
          <span className="shrink-0 text-faint">×</span>
          {fb && fb.flags[0] && <Flag code={fb.flags[0]} h={10} />}
          <span className="truncate text-fg-2">{e.b.name}</span>
        </div>
        <div className="mt-1.5 flex items-center gap-2 text-[10.5px]">
          {e.agentsWorking ? (
            <Chip color="var(--blue)" size="sm" icon={<Loader2 size={9} className="animate-spin" />}>
              Agents working
            </Chip>
          ) : (
            <Chip color={st.color} size="sm">
              {st.label}
            </Chip>
          )}
          <span className="mono tnum text-fg-2">{fmtMiss(e.missM)}</span>
          <span className="mono tnum flex items-center gap-0.5" style={{ color: resolved ? "var(--muted)" : RISK_COLOR[e.risk] }}>
            {fmtPc(e.pc)}
            <TrendIcon size={10} />
          </span>
        </div>
      </button>
      <AnimatePresence initial={false}>
        {focused && (
          <motion.div
            initial={{ height: 0, opacity: 0 }}
            animate={{ height: "auto", opacity: 1 }}
            exit={{ height: 0, opacity: 0 }}
            transition={{ duration: 0.3, ease: [0.22, 1, 0.36, 1] }}
            className="overflow-hidden"
          >
            <EventDetail e={e} />
          </motion.div>
        )}
      </AnimatePresence>
    </div>
  );
}

