/** Stable fallback: a new {} per render would loop the store subscription. */
const NO_OWNERS: Record<string, string> = {};

type Filter = "active" | "resolved";

export function ConjunctionQueue() {
  const dev = useOps((s) => s.dev);
  const events = useOps((s) => s.events);
  const lastScan = useOps((s) => s.lastScan);
  const scanning = useOps((s) => s.scanning);
  const focusEvent = useOps((s) => s.focusEvent);
  const [filter, setFilter] = useState<Filter>("active");
  const now = useNow(1000);
  // ranking moves slowly; minute resolution keeps rows from reshuffling every tick
  const rankAt = Math.floor(now / 60_000) * 60_000;

  const sorted = useMemo(() => {
    // the focused event stays where it is when it resolves, so its outcome is visible
    const isActive = (e: ConjunctionEvent) => !RESOLVED.includes(e.status) || e.id === focusEvent;
    const list = events.filter((e) => (filter === "resolved" ? !isActive(e) : isActive(e)));
    // red first, then by Pc / hours-to-TCA (Q-1)
    return list.sort((a, b) => {
      if (a.risk !== b.risk) return a.risk === "red" ? -1 : 1;
      const sa = a.pc / Math.max((a.tca - rankAt) / 3600_000, 1);
      const sb = b.pc / Math.max((b.tca - rankAt) / 3600_000, 1);
      return sb - sa;
    });
  }, [events, filter, rankAt, focusEvent]);

  // dev off: the backend's rows (events.catalogPairs); dev on: the synthetic scenarios
  const backendRows = useOps((s) => s.backendRows);
  const red = dev ? events.filter((e) => e.risk === "red" && !RESOLVED.includes(e.status)).length : (backendRows ?? []).filter((r) => r.color === "red").length;
  const active = dev ? events.filter((e) => !RESOLVED.includes(e.status)).length : (backendRows?.length ?? 0);
  const loadingBackend = !dev && (!CONVEX_ENABLED || backendRows === undefined);

  return (
    <motion.section
      initial={{ opacity: 0, x: -16, filter: "blur(8px)" }}
      animate={{ opacity: 1, x: 0, filter: "blur(0px)" }}
      exit={{ opacity: 0, x: -16, filter: "blur(8px)" }}
      transition={{ duration: 0.32, ease: [0.22, 1, 0.36, 1] }}
      className="glass pointer-events-auto relative flex min-h-0 flex-1 flex-col overflow-hidden rounded-[14px]"
    >
      {/* header */}
      <div className="px-3 pb-2 pt-3">
        <div className="flex items-center justify-between">
          <span className="eyebrow">Conjunction queue</span>
          {dev && (
            <Tooltip label="Generated by the dev simulator around real catalog objects">
              <span className="mono rounded-[4px] px-1 py-px text-[9px] font-medium uppercase tracking-[0.1em] text-orange shadow-[inset_0_0_0_1px_rgba(255,159,64,0.25)]">
                Synthetic
              </span>
            </Tooltip>
          )}
          {!dev && CONVEX_ENABLED && backendRows !== undefined && (
            <Tooltip label="Real conjunction pairs from the backend's catalog snapshot">
              <span className="mono rounded-[4px] px-1 py-px text-[9px] font-medium uppercase tracking-[0.1em] text-green shadow-[inset_0_0_0_1px_rgba(61,220,151,0.25)]">
                Live
              </span>
            </Tooltip>
          )}
        </div>
        <div className="mt-1.5 flex items-baseline gap-2">
          <span className="tnum text-[26px] font-semibold leading-none tracking-[-0.03em]">{loadingBackend ? "–" : active}</span>
          <span className="text-[11px] text-muted">
            {dev ? "active" : "conjunctions"}
            {red > 0 && (
              <>
                {" · "}
                <span className="text-red">{red} red</span>
              </>
            )}
          </span>
        </div>
        <div className="mt-2.5">
          <ScanButton />
        </div>
        {dev && <ScanLine scanning={scanning} lastScan={lastScan} now={now} />}
        {!dev && CONVEX_ENABLED && <BackendSnapshotLine now={now} />}
      </div>

      {/* filter (synthetic scenarios only: backend rows are all current and already in queue order) */}
      {dev && (
        <div className="flex items-center gap-0.5 px-2 pb-1.5">
          {(["active", "resolved"] as Filter[]).map((f) => (
            <button
              key={f}
              className="btn relative h-6 px-2 text-[11px]"
              data-active={filter === f}
              onClick={() => {
                sfx.click();
                setFilter(f);
              }}
            >
              {filter === f && <motion.span layoutId="queue-filter" className="seg-pill" transition={{ type: "spring", stiffness: 500, damping: 38 }} />}
              <span className="relative capitalize">{f}</span>
            </button>
          ))}
        </div>
      )}
      <div className="mx-3 h-px bg-white/[0.06]" />

      {/* list */}
      <div className="thin-scroll min-h-0 flex-1 overflow-y-auto px-1.5 py-1.5">
        {!dev && !CONVEX_ENABLED && <BackendEmpty />}
        {!dev && CONVEX_ENABLED && <BackendListSafe now={now} />}
        {dev && sorted.length === 0 && (
          <div className="px-3 py-8 text-center text-[11px] text-muted">
            {filter === "active" ? "Nothing needs a decision. The Risk Monitor keeps screening." : "No resolved events yet."}
          </div>
        )}
        <AnimatePresence initial={false}>
          {sorted.map((e) => (
            <motion.div
              key={e.id}
              layout="position"
              initial={{ opacity: 0, y: -8 }}
              animate={{ opacity: 1, y: 0 }}
              exit={{ opacity: 0, scale: 0.97 }}
              transition={{ duration: 0.28, ease: [0.22, 1, 0.36, 1] }}
            >
              <EventRow e={e} now={now} />
            </motion.div>
          ))}
        </AnimatePresence>
      </div>
    </motion.section>
  );
}

