export interface OwnerInfo {
  code: string;
  name: string; // short display name
  fullName: string; // SATCAT name
  flags: string[]; // ISO alpha-2, may be empty
  isOrg: boolean;
}

export function ownerInfo(code: string, owners: Record<string, string>): OwnerInfo | null {
  if (!code) return null;
  const fullName = owners[code] ?? EXTRA_OWNER_NAMES[code] ?? code;
  const flags = OWNER_FLAGS[code] ?? [];
  return {
    code,
    fullName,
    name: SHORT[code] ?? fullName.replace(/^(The |Republic of |Federal Democratic Republic of |Principality of |State of )/, ""),
    flags,
    isOrg: flags.length === 0,
  };
}
