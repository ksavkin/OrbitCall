import { v } from "convex/values";

export const side = v.union(v.literal("A"), v.literal("B"));
export const policyWindow = v.object({ startUtc: v.string(), endUtc: v.string(), reason: v.string() });
export const satellitePolicy = v.object({
  objectId: v.string(), minFuelReserveKg: v.number(), currentFuelKg: v.number(),
  dryMassKg: v.number(), ispS: v.number(),
  protectedWindows: v.array(policyWindow), preferredWindows: v.array(policyWindow),
  acceptablePc: v.number(), missionPriority: v.union(v.literal("low"), v.literal("normal"), v.literal("high")),
});
export const category = v.union(v.literal("fuel"), v.literal("mission_window"), v.literal("risk"), v.literal("priority"), v.literal("other"));
export const outcome = v.union(v.literal("feasible"), v.literal("infeasible"), v.literal("preferred"), v.literal("pending"));

// Phase 1 candidate input seam. IDs are stable within an event; revisions must increase on change.
// These are supplied by deterministic tools, never generated by the Advocate.
export const candidate = v.object({
  candidateId: v.string(), revision: v.number(), label: v.string(),
  kind: v.union(v.literal("maneuver"), v.literal("wait")),
  movingSide: v.union(side, v.null()), movingObjectId: v.union(v.string(), v.null()),
  burnTimeUtc: v.union(v.string(), v.null()), deltaVMs: v.union(v.number(), v.null()),
  direction: v.union(v.literal("prograde"), v.literal("retrograde"), v.null()),
  estimatedFuelKg: v.union(v.number(), v.null()), missBeforeKm: v.number(),
  missAfterKm: v.union(v.number(), v.null()), indicative: v.literal(true),
  reviewCondition: v.union(v.string(), v.null()), assumptions: v.array(v.string()), simulated: v.boolean(),
});
export const sharedEvaluation = v.object({
  candidateId: v.string(), revision: v.number(), outcome,
  categories: v.array(category), recommended: v.boolean(),
});
